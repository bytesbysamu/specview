import {
  Component,
  OnInit,
  inject,
  signal,
  computed,
} from '@angular/core';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import { marked } from 'marked';
import DOMPurify from 'dompurify';

import {
  LandingHandoffService,
  BootstrapFile,
  DemoResult,
} from '../landing-handoff.service';

const FILE_LABELS: Record<string, string> = {
  'analysis.md': 'Analysis',
  'epic.md': 'Epic',
  'architecture.md': 'Solution Architecture',
  'timeline.md': 'Timeline',
  'spec-index.md': 'Spec Index',
  'README.md': 'README',
};

const CANONICAL_ORDER = [
  'spec-index.md',
  'analysis.md',
  'epic.md',
  'architecture.md',
  'timeline.md',
  'README.md',
];

function sortFiles(files: BootstrapFile[]): BootstrapFile[] {
  return [...files].sort((a, b) => {
    const ia = CANONICAL_ORDER.indexOf(a.filename);
    const ib = CANONICAL_ORDER.indexOf(b.filename);
    return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib);
  });
}

/**
 * DemoResultComponent — displays a pre-computed spec result for a landing-page
 * demo slug. Fetches `public/demo/{slug}.json` on init and renders each file's
 * markdown content immediately — no loading state needed because the JSON fetch
 * is effectively instant from the same origin.
 */
@Component({
  selector: 'app-demo-result',
  standalone: true,
  template: `
    <div class="result-shell" data-test="demo-result-shell">
      @if (errorMsg()) {
        <div class="result-error" data-test="demo-result-error">
          <p>Could not load demo: {{ errorMsg() }}</p>
        </div>
      }

      @if (files().length > 0) {
        <div class="result-tabs" data-test="demo-result-tabs">
          @for (f of files(); track f.filename) {
            <button
              class="tab-btn"
              [class.active]="activeFilename() === f.filename"
              (click)="selectFile(f.filename)"
              data-test="demo-tab-btn"
            >
              {{ labelFor(f.filename) }}
            </button>
          }
        </div>

        <div class="result-content" data-test="demo-result-content">
          @if (parsedContent()) {
            <div
              class="markdown-body"
              [innerHTML]="parsedContent()"
              data-test="demo-markdown-body"
            ></div>
          }
        </div>

        <div class="conversion-gate" data-test="demo-conversion-gate">
          <p class="gate-prompt">
            This is a live preview generated by Specview.
            Sign up to create your own spec — free.
          </p>
          <a href="/signup" class="gate-cta" data-test="demo-signup-link">
            Create your first spec
          </a>
        </div>
      }
    </div>
  `,
  styles: [`
    .result-shell {
      display: flex;
      flex-direction: column;
      min-height: 100vh;
      max-width: 860px;
      margin: 0 auto;
      padding: 2rem 1.5rem;
      gap: 0;
    }

    .result-error {
      color: var(--color-error, #c0392b);
      padding: 1rem;
    }

    .result-tabs {
      display: flex;
      gap: 0.25rem;
      flex-wrap: wrap;
      border-bottom: 1px solid var(--color-border, #e0e0e0);
      margin-bottom: 1.5rem;
    }

    .tab-btn {
      padding: 0.5rem 1rem;
      border: none;
      background: none;
      cursor: pointer;
      font-size: 0.875rem;
      color: var(--color-text-muted, #666);
      border-bottom: 2px solid transparent;
      transition: color 0.15s, border-color 0.15s;
    }

    .tab-btn:hover {
      color: var(--color-text, #222);
    }

    .tab-btn.active {
      color: var(--color-accent, #1a73e8);
      border-bottom-color: var(--color-accent, #1a73e8);
      font-weight: 600;
    }

    .result-content {
      flex: 1;
    }

    .markdown-body {
      line-height: 1.7;
      font-size: 1rem;
      color: var(--color-text, #222);
    }

    .conversion-gate {
      margin-top: 3rem;
      padding: 2rem;
      background: var(--color-surface-alt, #f5f7fa);
      border-radius: 8px;
      text-align: center;
      border: 1px solid var(--color-border, #e0e0e0);
    }

    .gate-prompt {
      margin: 0 0 1rem;
      font-size: 1rem;
      color: var(--color-text, #222);
    }

    .gate-cta {
      display: inline-block;
      padding: 0.75rem 1.5rem;
      background: var(--color-accent, #1a73e8);
      color: #fff;
      border-radius: 6px;
      text-decoration: none;
      font-weight: 600;
      font-size: 0.9375rem;
      transition: opacity 0.15s;
    }

    .gate-cta:hover {
      opacity: 0.9;
    }
  `],
})
export class DemoResultComponent implements OnInit {
  private readonly handoffSvc = inject(LandingHandoffService);
  private readonly sanitizer = inject(DomSanitizer);
  readonly files = signal<BootstrapFile[]>([]);
  readonly activeFilename = signal<string | null>(null);
  readonly errorMsg = signal<string | null>(null);

  readonly parsedContent = computed<SafeHtml>(() => {
    const name = this.activeFilename();
    const f = this.files().find(x => x.filename === name);
    if (!f?.content) return '';
    const html = marked.parse(f.content) as string;
    return this.sanitizer.bypassSecurityTrustHtml(DOMPurify.sanitize(html));
  });

  ngOnInit(): void {
    const slug = this._resolveSlug();
    if (!slug) {
      this.errorMsg.set('No demo slug provided.');
      return;
    }
    this._loadDemo(slug);
  }

  selectFile(filename: string): void {
    this.activeFilename.set(filename);
  }

  labelFor(filename: string): string {
    return FILE_LABELS[filename] ?? filename.replace(/\.md$/i, '');
  }

  private _resolveSlug(): string | null {
    // Primary: from the handoff service (set by landing page redirect ?demo=<slug>)
    if (
      this.handoffSvc.handoff.mode === 'demo' &&
      this.handoffSvc.handoff.slug
    ) {
      return this.handoffSvc.handoff.slug;
    }
    // Fallback: read from current URL query params (Angular route)
    const params = new URLSearchParams(window.location.search);
    return params.get('demo');
  }

  private async _loadDemo(slug: string): Promise<void> {
    try {
      const result: DemoResult = await this.handoffSvc.fetchDemoResult(slug);
      const sorted = sortFiles(result.files ?? []);
      this.files.set(sorted);
      if (sorted.length > 0) {
        this.activeFilename.set(sorted[0].filename);
      }
    } catch (e: any) {
      this.errorMsg.set(
        e?.statusText ?? e?.message ?? `Demo "${slug}" not found.`
      );
    }
  }
}
